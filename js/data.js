export function orderStatusLabel(o) {
  switch (o.status) {
    case 'pending': return o.payMethod === 'cod' ? 'ثبت شد' : 'در انتظار پرداخت';
    case 'paid': return 'پرداخت شد';
    case 'shipped': return 'در راه';
    case 'delivered': return 'تحویل داده شد';
    default: return o.status;
  }
}
